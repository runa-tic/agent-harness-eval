"""Build the synthetic notes corpus and the task list with gold answers.

Everything is derived from one seed, so the corpus, the questions and the gold answers can be
regenerated byte for byte. The company, people and numbers are invented: nothing here can be
answered from a model's training data, only from the files.

Usage: python corpus_gen.py [out_dir]     (default: ./corpus, tasks land in ./tasks.json)
"""
import json, random, sys
from pathlib import Path

SEED = 20261010
ROOT = Path(__file__).resolve().parent

