def checks(T, v):
    """Properties the gold answers rely on. A change to the tables that breaks one fails here
    instead of silently producing a wrong reference answer."""
    assert len({t["id"] for t in T}) == len(T), "duplicate task id"
    by = sorted(v["by_comp"].values())
    assert by[-1] > by[-2], "A6 needs a unique worst component"
    assert v["platform_active"] != v["platform_all"], "A4 needs an ended contract"
    assert v["billing_eom"] and v["rp_failed_april"] >= 2 and v["rb_who"], "deploy-log facts missing"
    assert len(v["june"]) >= 2 and v["quiet"] and v["auth_down"] and v["not_affected"], "empty list task"
    assert MOVED["who"] not in v["ilse_line"] and v["on_call"]("2026-07-08") is None
    assert v["svc"]["route-planner"][3] != STALE_PORT["route-planner"]
    assert v["earlier"][0] != v["billing_owner"][0] or v["earlier"][0] != v["ledger_owner"][0]
    for t in T:
        for pat in t["must"] + ([t["trap"]] if t.get("trap") else []):
            re.compile(pat)
        # The reference answer itself must pass its own programmatic check.
        seg = t["gold"]
        assert all(re.search(m, seg, re.I | re.S) for m in t["must"]), f"{t['id']}: gold fails its own must"
        if t.get("trap") and t["id"] not in ("J1", "J2", "L4", "A4"):   # these golds quote the wrong value on purpose
            assert not re.search(t["trap"], seg, re.I | re.S), f"{t['id']}: gold trips its own trap"


