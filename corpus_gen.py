MONTHS = ["January", "February", "March", "April", "May", "June", "July", "August", "September", "October",
          "November", "December"]
NOT = r"\b(not|no|never|none|unknown|cannot|unable|nobody)\b|n't"
WORDS = ["zero", "one", "two", "three", "four", "five", "six", "seven", "eight", "nine", "ten"]


def date_re(iso):
    """The date in ISO form or written out, day-first or month-first."""
    y, mth, day = iso.split("-")
    mon = MONTHS[int(mth) - 1]
    mon = f"{mon[:3]}({mon[3:]})?\\.?" if len(mon) > 3 else mon
    dd = f"0?{int(day)}(st|nd|rd|th)?"
    return f"{iso}|{mon}\\s+{dd}\\b|\\b{dd}\\s+(of\\s+)?{mon}"


def money_re(n):
    return r"\b" + f"{n:,}".replace(",", r"[,.  ]?") + r"\b"


def num_re(n):
    return rf"\b({n}|{WORDS[n]})\b" if n < len(WORDS) else rf"\b{n}\b"


def surnames(names): return [n.split()[1] for n in names]


