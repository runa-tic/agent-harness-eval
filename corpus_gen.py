def deploy_log():
    """A year-to-date production deploy log, about 1,700 lines. Returns the text and the facts the
    tasks ask about, taken from the same state machine that wrote the lines."""
    rng = random.Random(SEED + 1)
    engineers = [p[0] for p in PEOPLE if p[1] not in ("Finance", "Support")]
    names = [s[0] for s in SERVICES]
    counter = {s: rng.randint(11, 60) for s in names}
    major = {s: i % 4 + 1 for i, s in enumerate(names)}
    history = {s: [] for s in names}             # versions that have been running, oldest first
    # Scripted end of March for billing: a good deploy, a newer one, a rollback to the first, then
    # a failed attempt. The version running at month end is the first of the four.
    scripted = {"2026-03-27": [("11:20", "billing", "deploy-ok")],
                "2026-03-30": [("10:05", "billing", "deploy-ok"), ("16:40", "billing", "rollback")],
                "2026-03-31": [("15:15", "billing", "deploy-failed")]}
    lines, facts = [], dict(failed={}, last_rollback={}, running_eod={})
    day = d("2026-01-02")
    while day <= d("2026-06-12"):
        iso = day.isoformat()
        if day.weekday() < 5:
            events = list(scripted.get(iso, []))
            for _ in range(rng.randint(12, 18)):
                svc = rng.choice(names)
                if svc == "billing" and "2026-03-27" <= iso <= "2026-03-31":
                    continue
                t = f"{rng.randint(8, 18):02d}:{rng.randint(0, 59):02d}"
                r = rng.random()
                events.append((t, svc, "deploy-ok" if r < 0.85 else "deploy-failed" if r < 0.96 else "rollback"))
            for t, svc, action in sorted(events):
                who = rng.choice(engineers)
                if action == "rollback" and len(history[svc]) < 2:
                    action = "deploy-ok"
                if action == "rollback":
                    target = history[svc][-2]
                    history[svc].append(target)
                    lines.append(f"{iso} {t} | {svc} | rollback to {target} | ok | {who}")
                    facts["last_rollback"][svc] = (iso, who)
                else:
                    counter[svc] += 1
                    ver = f"v{major[svc]}.{counter[svc]}"
                    ok = action == "deploy-ok"
                    if ok:
                        history[svc].append(ver)
                    else:
                        key = (svc, iso[:7])
                        facts["failed"][key] = facts["failed"].get(key, 0) + 1
                    lines.append(f"{iso} {t} | {svc} | deploy {ver} | {'ok' if ok else 'failed'} | {who}")
        facts["running_eod"][iso] = {s: (h[-1] if h else None) for s, h in history.items()}
        day += timedelta(days=1)
    head = ("# Production deploy log, 2026\n\nOne line per action, oldest first: time | service | action | result | who.\n"
            "A failed deploy leaves the previously running version in place. A rollback puts the named version back.\n\n")
    return head + "\n".join(lines) + "\n", facts


def handbook():
    rng = random.Random(SEED + 2)
    out = ["# Engineering handbook", "", "How we build and run software here. Sections are numbered; changes made after",
           "the last full revision are listed under Amendments at the end and take precedence over the section text.", ""]
    for i, title in enumerate(HANDBOOK_SECTIONS, 1):
        out += [f"## {i}. {title}", ""]
        body = [s.format(t=title.lower()) for s in rng.sample(HANDBOOK_FILLER, rng.randint(9, 13))]
        if title == "Code review":
            body.insert(3, "Every change needs two approvals from engineers other than the author before it is merged.")
            body.insert(4, "Approvals lapse when new commits are pushed.")
        if title == "Change size":
            body.insert(5, f"A change of more than {SPLIT_LINES} changed lines must be split before review; "
                           "generated files do not count toward the limit.")
        out += body + [""]
    n_review = HANDBOOK_SECTIONS.index("Code review") + 1
    out += ["## Amendments", "",
            "- 2026-02-03, amends section 30 (Documentation): diagrams are kept as source files, not screenshots.",
            f"- 2026-05-11, amends section {n_review} (Code review): a change to a tier-3 service needs one approval. "
            "Changes to tier-1 and tier-2 services still need two.",
            "- 2026-05-26, amends section 33 (Meetings): the weekly engineering meeting moves to Tuesdays.", ""]
    return "\n".join(out)


