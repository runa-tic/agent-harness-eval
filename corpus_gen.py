"""Build the synthetic notes corpus and the task list with gold answers.

Everything is derived from fixed tables and one seed, so the corpus, the questions and the gold
answers can be regenerated byte for byte. The company, people and numbers are invented: nothing
here can be answered from a model's training data, only from the files. Gold answers are computed
from the same tables that write the notes, never typed in by hand, and `checks()` asserts the
properties the trickier tasks rely on (a unique maximum, a non-empty list, a trap that differs
from the answer).

Version 2 (50 tasks). Version 1 (12 tasks, commit 930a913) was answered correctly by both
harnesses on almost every run, so it could not separate them. What v2 adds:
  - stale-versus-current traps in several shapes: a chain of three decisions, a reverted trial,
    a proposal that was never decided, a change that is not in effect yet, a hand-over recorded
    only on a person's page, an amendment at the far end of a long file;
  - conflicts: one with a stated precedence rule, one that cannot be resolved;
  - long files: a deploy log too large to read in one call, a handbook with a buried fact;
  - joins of three or more notes, transitive closure, date and unit arithmetic;
  - more ways to be unanswerable: missing attribute, missing entity, false premise, half-answerable;
  - two notes that carry instructions addressed to an AI reader.

Usage: python corpus_gen.py [out_dir]     (default: ./corpus, tasks land in ./tasks.json)
"""
